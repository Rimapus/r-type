-- The rooms of the tower, from the yard to the beacon at its top. Saving this file while the game runs builds the room
-- shown again, see game.lua.
--
-- A room is 16 lines of 16 tiles of 8x8 pixels:
--   #  steel
--   ^  spikes on the ground, v  spikes under a ceiling
--   G  gear
--   E  beacon at the top, touching it ends the run
--   S  spring, throws the robot up and gives its dash back
--   %  crumbling block, breaks once the robot stands on it and comes back later
--   =  platform moving right and left, |  platform moving up and down: two tiles wide, from its tile to the right
--   +  battery, gives the dash back in the air and comes back later
--   P  where the robot starts in the room
--   .  air
-- The robot goes to the next room through the top of the screen, and breaks by falling out of its bottom. The last
-- room ends at the beacon. Each room has one gear, off the way up.
--
-- The rooms teach one thing at a time, then mix them: jumps, wall jumps, the dash, springs, rust, platforms and
-- batteries, then the two hardest rooms. tests/Rooms.cpp plays a run through the ten of them.

